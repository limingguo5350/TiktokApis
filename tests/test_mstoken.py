def test_response_header_token_replaces_stale_storage_and_cookie_copies():
    auth = TiktokAuth.from_cookie('other=ok; msToken=old',
        session_storage={'msToken': 'old-session'}, local_storage={'msToken': 'old-local'},
        document_cookie='other=ok; msToken=old-document')
    auth.apply_set_cookie(Headers({'x-ms-token': 'fresh-response'}))
    assert auth.ms_token == 'fresh-response'
    assert auth.cookie['msToken'] == 'fresh-response'
    assert auth.session_storage['msToken'] == 'fresh-response'
    assert auth.local_storage['msToken'] == 'fresh-response'
    assert auth.document_cookie == 'other=ok; msToken=fresh-response'


def test_response_token_header_has_precedence_over_set_cookie_and_ignores_invalid():
    auth = TiktokAuth.from_cookie('msToken=old', session_storage={'msToken': 'old'})
    auth.apply_set_cookie(Headers({'set-cookie': 'msToken=cookie-token; Path=/',
                                  'X-Ms-Token': 'header-token'}))
    assert auth.ms_token == 'header-token'
    auth.apply_set_cookie(Headers({'x-ms-token': 'bad\r\ntoken'}))
    assert auth.ms_token == 'header-token'
    auth.apply_set_cookie(Headers({'set-cookie': 'msToken=cookie-only; Path=/'}))
    assert auth.ms_token == 'cookie-only'
