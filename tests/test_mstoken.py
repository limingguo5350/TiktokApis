def test_refresh_reports_previous_token_and_fresh_sequence(monkeypatch):
    fingerprints = []
    def observe(data):
        fingerprints.append(data)
        return {'strData': 'not-sent-to-network'}
    monkeypatch.setattr('utils.mstoken.build_report', observe)
    client = MsTokenClient(session=Session(response('one'), response('two')))
    client.get_token()
    client.refresh()
    assert [f['tokenList'] for f in fingerprints] == [[], ['one']]
    assert [f['wID']['seq'] for f in fingerprints] == [[1, 1], [2, 2]]


