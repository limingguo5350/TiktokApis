ACK = {'maigc': 538051346, 'version': 1, 'dataType': 8}


class Headers(dict):
    def get_list(self, key):
        value = self.get(key, '')
        return value if isinstance(value, list) else [value]


def response(token='server-issued-test-token', *, ack=None, status=200, headers=None):
    return SimpleNamespace(status_code=status, json=lambda: ACK if ack is None else ack,
                           headers=Headers({'x-ms-token': token} if headers is None else headers))


class Session:
    def __init__(self, *replies):
        self.replies = list(replies)
        self.calls = []
        self.closed = False

    def post(self, url, **kwargs):
        self.calls.append((url, kwargs))
        reply = self.replies.pop(0)
        if isinstance(reply, Exception):
            raise reply
        return reply

    def close(self):
        self.closed = True


@pytest.mark.parametrize('vector', json.loads(
    Path(__file__).with_name('fixtures').joinpath('mstoken_vectors.json').read_text()))
def test_native_sdk_synthetic_vectors(vector):
    # Generated by the unmodified 1.0.0.417 SDK s1 encoder, compression disabled.
    assert encode_strdata(vector['plain'].encode(), key_words=vector['key']) == vector['encoded']


