@pytest.mark.parametrize('bad', [
    response(ack={'code': 5}), response(ack={**ACK, 'code': 5}),
    response(ack=[]), response(ack={'magic': 538051346, 'version': 1, 'dataType': 8}),
    response(status=403), response(status=302), response(token=''),
    response(token='bad\r\nvalue'), ValueError('secret-transport-payload'),
])
def test_failed_refresh_keeps_accepted_state_and_sanitizes_errors(bad):
    client = MsTokenClient(session=Session(response('accepted'), bad))
    assert client.get_token() == 'accepted'
    with pytest.raises(MsTokenError) as error:
        client.refresh()
    assert 'secret-transport-payload' not in str(error.value)
    assert client.get_token() == 'accepted'
    assert client._sequence == 1


def test_non_json_response():
    def invalid_json():
        raise ValueError('private body')
    client = MsTokenClient(session=Session(SimpleNamespace(status_code=200, json=invalid_json)))
    with pytest.raises(MsTokenError, match='not JSON'):
        client.get_token()


def test_independent_sessions_and_external_session_ownership():
    a, b = Session(response('one')), Session(response('two'))
    ca, cb = MsTokenClient(session=a), MsTokenClient(session=b)
    assert ca.get_token() == 'one'
    assert cb.get_token() == 'two'
    ca.close()
    assert not a.closed
    with pytest.raises(MsTokenError, match='closed'):
        ca.get_token()
    assert cb.get_token() == 'two'


def test_auth_preserves_external_token_without_network():
    auth = TiktokAuth.from_cookie('other=keep; msToken=external')
    assert auth.ensure_ms_token() == 'external'
    assert auth._ms_token_client is None


def test_auth_refresh_updates_all_copies_and_preserves_other_state():
    auth = TiktokAuth.from_cookie(
        'other=keep; msToken=old-cookie; other=duplicate',
        session_storage={'msToken': 'old-session', 'other': 'keep'},
        local_storage={'msToken': 'old-local'}, document_cookie='visible=keep; msToken=old-document')
    session = Session(response('renewed'))
    client = MsTokenClient(session=session, user_agent=auth.user_agent)
    assert auth.refresh_ms_token(client=client) == 'renewed'
    assert session.calls[0][1]['headers']['cookie'] == 'msToken=old-session'
    assert auth.ms_token == auth.cookie['msToken'] == auth.local_storage['msToken'] == 'renewed'
    assert auth.cookie_str == 'other=keep; msToken=renewed; other=duplicate'
    assert auth.document_cookie == 'visible=keep; msToken=renewed'
    assert auth.session_storage['other'] == 'keep'
    auth.close_ms_token_client()
    assert client.get_token() == 'renewed'  # external client remains usable


def test_auth_failed_refresh_does_not_replace_storages():
    auth = TiktokAuth.from_cookie('msToken=old', session_storage={'msToken': 'old-session'})
    client = MsTokenClient(session=Session(response(ack={'code': 5})), user_agent=auth.user_agent)
    with pytest.raises(MsTokenError):
        auth.refresh_ms_token(client=client)
    assert auth.ms_token == 'old-session'
    assert auth.cookie_str == 'msToken=old'


def test_auth_manages_default_client_cache_and_close(monkeypatch):
    session = Session(response('one'), response('two'))
    monkeypatch.setattr('curl_cffi.requests.Session', lambda **kw: session)
    auth = TiktokAuth()
    assert auth.ensure_ms_token(proxy='http://configured-proxy') == 'one'
    client = auth._ms_token_client
    assert auth.ensure_ms_token() == 'one'
    assert len(session.calls) == 1
    assert auth.refresh_ms_token() == 'two'
    with pytest.raises(ValueError, match='before changing'):
        auth.ensure_ms_token(proxy='http://other-proxy')
    auth.close_ms_token_client()
    assert session.closed
    assert auth._ms_token_client is None
    with pytest.raises(MsTokenError, match='closed'):
        client.get_token()


