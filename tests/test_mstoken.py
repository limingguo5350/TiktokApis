def test_random_keys_and_report_envelope():
    a = build_report({'test': '测试'}, timestamp_ms=123)
    b = build_report({'test': '测试'}, timestamp_ms=124)
    assert a['strData'] != b['strData']
    assert {k: v for k, v in a.items() if k != 'strData'} == {
        'magic': 538969122, 'version': 1, 'dataType': 8, 'tspFromClient': 123}


def test_fingerprint_dynamic_fields_and_profile_isolation():
    profile = {'navigator': {}, 'wID': {}, 'customInit': {'configured': True}}
    data = build_fingerprint(user_agent=TiktokAuth.UA, token='prior', sequence=2,
                             timestamp_ms=123, profile=profile)
    assert data['navigator']['platform'] == 'Win32'
    assert data['wID']['timestamp'] == '123'
    assert data['wID']['seq'] == [2, 2]
    assert data['tokenList'] == ['prior']
    assert data['customInit'] == {'configured': True}
    assert profile['wID'] == {}


def test_cache_expiry_refresh_and_previous_token(monkeypatch):
    session = Session(response('first'), response('second'), response('third'))
    clock = [100.0]
    monkeypatch.setattr('utils.mstoken.time.monotonic', lambda: clock[0])
    client = MsTokenClient(session=session, cache_seconds=10)
    assert client.get_token() == client.get_token() == 'first'
    assert len(session.calls) == 1
    assert client.refresh() == 'second'
    assert session.calls[1][1]['headers']['cookie'] == 'msToken=first'
    clock[0] = 111.0
    assert client.get_token() == 'third'
    assert session.calls[2][1]['headers']['cookie'] == 'msToken=second'
    assert client._sequence == 3
    assert session.calls[0][1]['allow_redirects'] is False


